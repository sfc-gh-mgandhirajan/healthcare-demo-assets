@app.post("/data/chat")
async def chat(body: ChatRequest):
    cortex_host = os.environ.get("CORTEX_HOST", os.environ.get("SNOWFLAKE_HOST", ""))
    pat = os.environ.get("CORTEX_CODE_PAT", "")
    token_path = Path("/snowflake/session/token")
    if pat:
        token = pat
        host = cortex_host
    elif token_path.exists():
        token = token_path.read_text().strip()
        host = cortex_host
    else:
        token = os.environ.get("SNOWFLAKE_PAT", "")
        host = cortex_host
        if not token or not host:
            raise HTTPException(
                status_code=503,
                detail="Cortex Agent requires CORTEX_HOST + auth token"
            )

    system_prompt = _build_system_prompt(body.claim_context)
    payload = {
        "messages": [
            *[{"role": m.role, "content": [{"type": "text", "text": m.content}]} for m in body.messages if m.content and m.content.strip()],
        ],
        "instructions": {
            "system": system_prompt,
        },
        "tools": [
            {
                "tool_spec": {
                    "type": "cortex_search",
                    "name": "payer_doc_search",
                }
            },
            {
                "tool_spec": {
                    "type": "cortex_analyst_text_to_sql",
                    "name": "claims_analyst",
                }
            },
        ],
        "tool_resources": {
            "payer_doc_search": {
                "search_service": SEARCH_SERVICE,
            },
            "claims_analyst": {
                "semantic_view": SEMANTIC_VIEW_FQN,
                "execution_environment": {
                    "type": "warehouse",
                    "warehouse": WH,
                },
            },
        },
    }

    async def stream_response():
        try:
            async with httpx.AsyncClient(timeout=120.0) as client:
                async with client.stream(
                    "POST",
                    f"https://{host}/api/v2/cortex/agent:run",
                    headers={
                        "Authorization": f"Bearer {token}",
                        "Content-Type": "application/json",
                        "Accept": "text/event-stream",
                    },
                    json=payload,
                ) as resp:
                    if resp.status_code != 200:
                        error_body = await resp.aread()
                        logger.error(f"Cortex Agent API error {resp.status_code}: {error_body.decode()[:500]}")
                        yield f"data: {{\"error\": \"Cortex Agent API returned {resp.status_code}\"}}\n\n"
                        return
                    async for chunk in resp.aiter_text():
                        if chunk:
                            yield chunk
        except Exception as e:
            logger.exception("Error streaming from Cortex Agent API")
            yield f"data: {{\"error\": \"{str(e)[:200]}\"}}\n\n"

    return StreamingResponse(
        stream_response(),
        media_type="text/event-stream",
        headers={
            "X-Accel-Buffering": "no",
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
        },
    )


