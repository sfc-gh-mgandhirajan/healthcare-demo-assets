def _get_connection():
    token_path = Path("/snowflake/session/token")
    if token_path.exists():
        creds: dict[str, Any] = {
            "host": os.environ.get("SNOWFLAKE_HOST"),
            "account": os.environ.get("SNOWFLAKE_ACCOUNT"),
            "authenticator": "oauth",
            "token": token_path.read_text().strip(),
            "warehouse": WH,
            "database": DB,
            "schema": SCHEMA,
            "client_session_keep_alive": True,
        }
        spcs_port = os.environ.get("SNOWFLAKE_PORT")
        if spcs_port:
            creds["port"] = int(spcs_port)
            creds["protocol"] = "https"
        logger.info(f"SPCS connect: host={creds['host']}, account={creds['account']}")
        return snowflake.connector.connect(**creds)
    return snowflake.connector.connect(
        connection_name=os.getenv("SNOWFLAKE_CONNECTION_NAME", "default")
    )


def _query(sql: str, params: tuple = ()) -> list[dict]:
    conn = _get_connection()
    try:
        cur = conn.cursor(snowflake.connector.DictCursor)
        cur.execute(sql, params)
        return [dict(r) for r in cur.fetchall()]
    finally:
        conn.close()


def _serialize(rows: list[dict]) -> list[dict]:
    out = []
    for r in rows:
        row = {}
        for k, v in r.items():
            if hasattr(v, "isoformat"):
                row[k] = v.isoformat()
            elif isinstance(v, (int, float, str, bool, type(None))):
                row[k] = v
            else:
                row[k] = str(v)
        out.append(row)
    return out


def _execute(sql: str, params: tuple = ()):
    conn = _get_connection()
    try:
        cur = conn.cursor()
        cur.execute(sql, params)
    finally:
        conn.close()


def _execute_put(local_path: str, stage_path: str):
    conn = _get_connection()
    try:
        cur = conn.cursor()
        cur.execute(f"PUT 'file://{local_path}' '{stage_path}' AUTO_COMPRESS=FALSE OVERWRITE=TRUE")
    finally:
        conn.close()


def _build_docx(
    provider_name: str, provider_npi: str, member_name: str, member_id: str,
    plan_id: str, dos: str, claim_id: str, denial_id: str,
    denial_code: str, denial_reason: str, appeal_body: str, policy_citations: str,
) -> BytesIO:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)
    style.font.color.rgb = RGBColor(0x33, 0x33, 0x33)

    draft = doc.add_paragraph()
    draft.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = draft.add_run("DRAFT — GENERATED BY AI AGENT")
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0xCC, 0x00, 0x00)
    run.bold = True

    header_para = doc.add_paragraph()
    header_para.space_after = Pt(4)
    run = header_para.add_run(provider_name or "Provider")
    run.bold = True
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(0x11, 0x56, 0x7F)

    sub = doc.add_paragraph()
    sub.space_after = Pt(2)
    sub.add_run(f"NPI: {provider_npi or 'N/A'}").font.size = Pt(9)

    from datetime import datetime
    date_para = doc.add_paragraph()
    date_para.space_after = Pt(16)
    date_para.add_run(datetime.now().strftime("%B %d, %Y")).font.size = Pt(10)

    doc.add_paragraph("")

    re_block = doc.add_paragraph()
    re_block.space_after = Pt(12)
    run = re_block.add_run("RE: Appeal of Claim Denial\n")
    run.bold = True
    run.font.size = Pt(11)
    for line in [
        f"Claim Number: {claim_id}",
        f"Member: {member_name}, ID: {member_id}",
        f"Plan: {plan_id}",
        f"Date of Service: {dos}",
        f"Denial Code: {denial_code} — {denial_reason}",
    ]:
        re_block.add_run(f"{line}\n").font.size = Pt(10)

    doc.add_paragraph("")

    for para_text in (appeal_body or "").split("\n\n"):
        para_text = para_text.strip()
        if not para_text:
            continue
        p = doc.add_paragraph()
        p.space_after = Pt(8)
        p.add_run(para_text).font.size = Pt(11)

    if policy_citations and policy_citations.strip():
        doc.add_paragraph("")
        ch = doc.add_paragraph()
        ch.space_after = Pt(4)
        run = ch.add_run("Policy Citations Referenced")
        run.bold = True
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(0x11, 0x56, 0x7F)
        for c in policy_citations.split(","):
            c = c.strip()
            if c:
                cp = doc.add_paragraph(style="List Bullet")
                cp.add_run(c).font.size = Pt(10)

    doc.add_paragraph("")
    sig = doc.add_paragraph()
    sig.add_run("Sincerely,\n").font.size = Pt(11)
    sig.add_run("\n")
    run = sig.add_run(provider_name or "Provider")
    run.bold = True
    run.font.size = Pt(11)
    sig.add_run(f"\nNPI: {provider_npi or 'N/A'}").font.size = Pt(10)

    buf = BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


@app.get("/data/queue")
async def get_queue(unprocessed: bool = False):
    filter_clause = "WHERE d.PROCESSED_BY_AGENT = false" if unprocessed else ""
    sql = f"""
    SELECT d.DENIAL_ID, d.CLAIM_ID, d.DENIAL_CODE, d.DENIAL_REASON, d.DENIAL_AMOUNT,
           d.DENIAL_DATE, d.PAYER_REMARK,
           d.PROCESSED_BY_AGENT, d.AGENT_PROCESSED_AT,
           c.PROVIDER_NAME, c.DATE_OF_SERVICE, c.TOTAL_BILLED,
           c.PRIMARY_DIAGNOSIS, c.DIAGNOSIS_DESCRIPTION, c.PROVIDER_NPI, c.GROUP_NPI,
           c.FACILITY_NAME, c.PAYER_ID,
           m.FIRST_NAME || ' ' || m.LAST_NAME AS PATIENT_NAME,
           m.MEMBER_ID, m.PLAN_ID
    FROM {DB}.{SCHEMA}.DENIALS d
    JOIN {DB}.{SCHEMA}.CLAIMS c ON d.CLAIM_ID = c.CLAIM_ID
    JOIN {DB}.{SCHEMA}.MEMBERS m ON c.MEMBER_ID = m.MEMBER_ID
    {filter_clause}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY d.CLAIM_ID ORDER BY d.PROCESSED_BY_AGENT DESC, d.DENIAL_ID) = 1
    ORDER BY d.DENIAL_AMOUNT DESC
    """
    rows = _serialize(_query(sql))
    return {"denials": rows, "count": len(rows)}


@app.get("/data/results/{claim_id}")
async def get_results(claim_id: str):
    denial_sql = f"""
    SELECT d.DENIAL_ID, d.CLAIM_ID, d.DENIAL_CODE, d.DENIAL_REASON, d.DENIAL_AMOUNT,
           d.PROCESSED_BY_AGENT, d.AGENT_RESULT,
           c.PROVIDER_NAME, c.DATE_OF_SERVICE, c.TOTAL_BILLED,
           c.PRIMARY_DIAGNOSIS, c.DIAGNOSIS_DESCRIPTION, c.PROVIDER_NPI,
           m.FIRST_NAME || ' ' || m.LAST_NAME AS PATIENT_NAME, m.MEMBER_ID, m.PLAN_ID
    FROM {DB}.{SCHEMA}.DENIALS d
    JOIN {DB}.{SCHEMA}.CLAIMS c ON d.CLAIM_ID = c.CLAIM_ID
    JOIN {DB}.{SCHEMA}.MEMBERS m ON c.MEMBER_ID = m.MEMBER_ID
    WHERE d.CLAIM_ID = %s
    ORDER BY d.PROCESSED_BY_AGENT DESC
    LIMIT 1
    """
    denials = _query(denial_sql, (claim_id,))
    if not denials:
        raise HTTPException(status_code=404, detail=f"Claim {claim_id} not found")
    denial = denials[0]

    agent_result_raw = denial.pop("AGENT_RESULT", None)
    agent_result = None
    if agent_result_raw:
        if isinstance(agent_result_raw, str):
            try:
                agent_result = json.loads(agent_result_raw)
            except Exception:
                agent_result = None
        elif isinstance(agent_result_raw, dict):
            agent_result = agent_result_raw

    work_items = _query(
        f"SELECT * FROM {DB}.{SCHEMA}.DENIAL_WORK_ITEMS WHERE CLAIM_ID = %s ORDER BY CREATED_AT DESC",
        (claim_id,),
    )
    notes = _query(
        f"SELECT * FROM {DB}.{SCHEMA}.DENIAL_NOTES WHERE CLAIM_ID = %s ORDER BY CREATED_AT DESC",
        (claim_id,),
    )
    drafts = _query(
        f"SELECT * FROM {DB}.{SCHEMA}.APPEAL_DRAFTS WHERE CLAIM_ID = %s ORDER BY CREATED_AT DESC",
        (claim_id,),
    )

    return {
        "denial": _serialize([denial])[0],
        "agent_result": agent_result,
        "work_items": _serialize(work_items),
        "notes": _serialize(notes),
        "appeal_drafts": _serialize(drafts),
    }


