def _reset_claims(claim_ids: list[str]):
    placeholders = ",".join(["%s"] * len(claim_ids))
    params = tuple(claim_ids)
    _execute(
        f"DELETE FROM {DB}.{SCHEMA}.DENIAL_WORK_ITEMS WHERE CREATED_BY = 'DENIAL_AGENT' AND CLAIM_ID IN ({placeholders})",
        params,
    )
    _execute(
        f"DELETE FROM {DB}.{SCHEMA}.DENIAL_NOTES WHERE CREATED_BY = 'DENIAL_AGENT' AND CLAIM_ID IN ({placeholders})",
        params,
    )
    _execute(
        f"DELETE FROM {DB}.{SCHEMA}.APPEAL_DRAFTS WHERE CREATED_BY = 'DENIAL_AGENT' AND CLAIM_ID IN ({placeholders})",
        params,
    )
    _execute(
        f"UPDATE {DB}.{SCHEMA}.DENIALS SET PROCESSED_BY_AGENT = false, AGENT_RESULT = NULL, AGENT_PROCESSED_AT = NULL WHERE CLAIM_ID IN ({placeholders})",
        params,
    )
    for cid in claim_ids:
        try:
            _execute(f"REMOVE @{DB}.{SCHEMA}.APPEAL_DOCUMENTS/{cid}/")
        except Exception:
            pass


def _restore_seed():
    _execute(f"INSERT INTO {DB}.{SCHEMA}.DENIAL_WORK_ITEMS SELECT * FROM {DB}.{SCHEMA}.SEED_DENIAL_WORK_ITEMS")
    _execute(f"INSERT INTO {DB}.{SCHEMA}.DENIAL_NOTES SELECT * FROM {DB}.{SCHEMA}.SEED_DENIAL_NOTES")
    _execute(f"INSERT INTO {DB}.{SCHEMA}.APPEAL_DRAFTS SELECT * FROM {DB}.{SCHEMA}.SEED_APPEAL_DRAFTS")
    _execute(
        f"UPDATE {DB}.{SCHEMA}.DENIALS d SET d.PROCESSED_BY_AGENT = true, "
        f"d.AGENT_RESULT = s.AGENT_RESULT, d.AGENT_PROCESSED_AT = s.AGENT_PROCESSED_AT "
        f"FROM {DB}.{SCHEMA}.SEED_DENIALS_AGENT_STATE s WHERE d.DENIAL_ID = s.DENIAL_ID"
    )
    try:
        _execute(
            f"COPY FILES INTO @{DB}.{SCHEMA}.APPEAL_DOCUMENTS/ "
            f"FROM @{DB}.{SCHEMA}.SEED_APPEAL_DOCUMENTS/"
        )
    except Exception as e:
        logger.warning(f"Failed to restore seed DOCX files: {e}")


@app.post("/data/reset")
async def reset_demo(body: ResetRequest | None = None):
    if body and body.claim_ids:
        _reset_claims(body.claim_ids)
        logger.info(f"Selective reset completed for {body.claim_ids}")
        return {"status": "reset_complete", "mode": "selective", "claim_ids": body.claim_ids}

    _execute(f"DELETE FROM {DB}.{SCHEMA}.DENIAL_WORK_ITEMS WHERE CREATED_BY = 'DENIAL_AGENT'")
    _execute(f"DELETE FROM {DB}.{SCHEMA}.DENIAL_NOTES WHERE CREATED_BY = 'DENIAL_AGENT'")
    _execute(f"DELETE FROM {DB}.{SCHEMA}.APPEAL_DRAFTS WHERE CREATED_BY = 'DENIAL_AGENT'")
    _execute(f"UPDATE {DB}.{SCHEMA}.DENIALS SET PROCESSED_BY_AGENT = false, AGENT_RESULT = NULL, AGENT_PROCESSED_AT = NULL WHERE PROCESSED_BY_AGENT = true")
    try:
        _execute(f"REMOVE @{DB}.{SCHEMA}.APPEAL_DOCUMENTS")
    except Exception:
        pass

    mode = (body.mode if body else "seed") or "seed"
    if mode == "seed":
        _restore_seed()
        logger.info("Full reset — seed state restored (6 processed + 1 unprocessed)")
        return {"status": "reset_complete", "mode": "seed"}

    logger.info("Full reset — clean slate")
    return {"status": "reset_complete", "mode": "clean"}
